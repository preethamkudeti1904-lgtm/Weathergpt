/**
 * Translates a raw weather condition into the user's selected language
 */
export function translateCondition(condition: string = "", lang: LanguageCode = 'en'): string {
  if (!condition || lang === 'en') return condition;

  const key = condition.trim().toLowerCase();
  const match = WEATHER_CONDITIONS_MAP[key];
  if (match && match[lang]) {
    return match[lang];
  }

  // Partial matches
  for (const [condKey, langMap] of Object.entries(WEATHER_CONDITIONS_MAP)) {
    if (key.includes(condKey) || condKey.includes(key)) {
      if (langMap[lang]) return langMap[lang];
    }
  }

  return condition;
}
